const DEFAULT_LANGUAGE = "en-US";

/**
 * Resolve a stored language code to its string set, falling back to
 * en-US when unset or not recognized.
 */
function getPoEmailStrings(languageCode) {
  return PO_EMAIL_STRINGS[languageCode] || PO_EMAIL_STRINGS[DEFAULT_LANGUAGE];
}

/**
 * Interpolates `{{placeholder}}` tokens in a template string. Values are
 * inserted verbatim — callers must HTML-escape any dynamic value themselves
 * before passing it in (see esc() in sendPoEmails.js) since this module has
 * no HTML context of its own.
 */
function t(strings, key, vars) {
  const template = strings[key] != null ? strings[key] : PO_EMAIL_STRINGS[DEFAULT_LANGUAGE][key];
  if (template == null) return "";
  if (!vars) return template;
  return template.replace(/\{\{(\w+)\}\}/g, (match, name) =>
    Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : match,
  );
}

module.exports = {
  PO_EMAIL_STRINGS,
  DEFAULT_LANGUAGE,
  getPoEmailStrings,
  t,
};
